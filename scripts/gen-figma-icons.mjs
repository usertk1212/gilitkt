/**
 * Regenerates src/app/components/icons/figma.tsx from the SVGs exported out of
 * the GILI Figma file (src/app/assets/icons/*.svg).
 *
 * The raw Figma exports are unusable as-is, for three reasons:
 *
 *   1. They carry the literal fill colour the icon happened to have in the
 *      mockup, so they ignore the theme.
 *   2. preserveAspectRatio="none" stretches the glyph to whatever box it lands in.
 *   3. The viewBox is the glyph's own bounding box, NOT the icon frame. Figma
 *      exports the "Icon (Stroke)" layer, which in the design sits inset inside
 *      a 24-grid frame — compass-03 exports as 18.3333 wide because its glyph
 *      spans 22 of 24 grid units at 20px display size. Rendered as-is the glyph
 *      fills the whole box, so every icon comes out 5–50% too large and the set
 *      no longer optically aligns.
 *
 * PAD fixes (3): it records how far each glyph is inset within the 24-unit
 * frame, read off the `inset-[...]` values in the Figma design context. The
 * viewBox is then widened back out to the full frame, which restores the
 * intended size and centring without touching the path data.
 *
 * Run with: node scripts/gen-figma-icons.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src/app/assets/icons");
const outFile = join(root, "src/app/components/icons/figma.tsx");

const GRID = 24;

/**
 * Inset of each glyph inside its 24-unit frame, as [top, right, bottom, left].
 * A single number is shorthand for all four sides; two numbers for [y, x].
 *
 * These come from the `inset-[...]` percentages Figma reports for the icon in
 * the design (4.17% of the frame = 1 unit of 24). An icon missing from this map
 * is assumed to be flush to its frame, which is right for the few glyphs that
 * genuinely bleed to the edge and merely a touch large for anything else.
 */
const PAD = {
  "atom-02": [2.16, 2.12],
  "chevron-down": [8, 5],
  "chevron-left": [5, 8],
  "chevron-right": [5, 8],
  "chevron-selector-vertical": [3, 6],
  check: [5, 3, 6, 3],
  "compass-03": 1,
  "copy-03": 1,
  "cube-01": [1.14, 2],
  "edit-02": 1,
  "file-download-01": 1,
  "file-download-02": 1,
  "image-01": 2,
  island: 1,
  "layout-left": 2,
  plus: 4,
  "puzzle-piece-02": 1,
  "search-lg": 2,
  "sticker-circle": 1,
  "trash-03": [1.5, 2.5],
};

const sides = (name) => {
  const p = PAD[name] ?? 0;
  if (Array.isArray(p)) {
    const [y, x] = p;
    return { top: y, right: x, bottom: y, left: x };
  }
  return { top: p, right: p, bottom: p, left: p };
};

const entries = readdirSync(srcDir)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((file) => {
    const key = basename(file, ".svg");
    const raw = readFileSync(join(srcDir, file), "utf8");

    const box = raw.match(/viewBox="([^"]+)"/)?.[1];
    if (!box) throw new Error(`${file}: no viewBox`);

    const [, , w, h] = box.split(/\s+/).map(Number);
    if (!w || !h) throw new Error(`${file}: unusable viewBox "${box}"`);

    // How many SVG units one 24-grid unit is worth, measured on each axis
    // independently — a few glyphs are exported very slightly non-square.
    const { top, right, bottom, left } = sides(key);
    const unitX = w / (GRID - left - right);
    const unitY = h / (GRID - top - bottom);

    // Icon frames are square. Where the two axes disagree — because a glyph is
    // exported slightly off-square, or because the inset above is an estimate —
    // take the larger frame and centre the glyph in it. That keeps every icon
    // on one grid and, unlike scaling an axis to fit, cannot distort the shape.
    const frame = Math.max(GRID * unitX, GRID * unitY);
    const viewBox = [
      -(left * unitX) - (frame - GRID * unitX) / 2,
      -(top * unitY) - (frame - GRID * unitY) / 2,
      frame,
      frame,
    ]
      .map((n) => Number(n.toFixed(4)))
      .join(" ");

    const body = raw
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .replace(/\s*id="[^"]*"/g, "")
      .replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"')
      .replace(/stroke="(?!none)[^"]*"/g, 'stroke="currentColor"')
      .trim();

    return { key, viewBox, body };
  });

const toPascal = (name) =>
  name.split(/[-_]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");

const out = `// AUTO-GENERATED by scripts/gen-figma-icons.mjs — do not edit by hand.
// Source: the GILI Figma file (tYtIgjjq8w07pZEZbJB0s0), exported to
// src/app/assets/icons/. Fills are rewritten to currentColor so the glyphs
// inherit text colour and work in dark mode, and each viewBox is widened from
// the exported glyph bounding box back out to the icon's full 24-unit frame so
// the set renders at the size the design draws it.
//
// These are the outline icons the revamp design uses. They are deliberately a
// separate registry from ./index.tsx, whose glyphs are the older solid set.
import { memo, type SVGProps } from "react";

type Glyph = { viewBox: string; body: string };

const G: Record<string, Glyph> = {
${entries
  .map((e) => `  ${JSON.stringify(e.key)}: { viewBox: ${JSON.stringify(e.viewBox)}, body: ${JSON.stringify(e.body)} },`)
  .join("\n")}
};

function make(key: string) {
  const { viewBox, body } = G[key];
  const C = (props: SVGProps<SVGSVGElement>) => (
    <svg
      width="24"
      height="24"
      viewBox={viewBox}
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      focusable="false"
      {...props}
      dangerouslySetInnerHTML={{ __html: body }}
    />
  );
  C.displayName = ${JSON.stringify("Figma")} + key;
  return memo(C);
}

${entries.map((e) => `export const ${toPascal(e.key)} = make(${JSON.stringify(e.key)});`).join("\n")}
`;

writeFileSync(outFile, out);
console.log(`wrote ${outFile} (${entries.length} icons)`);
